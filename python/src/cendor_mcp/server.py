"""cendor-mcp — the Python (uvx) twin of the read-only Cendor docs MCP server.

Same five read-only tools, same answers as the TypeScript server (npx @cendor/mcp / the Cloudflare
Worker). Both read the SAME generated index (data/index.json, produced by scripts/build-index.mjs
from the sibling docs — never a copy of the docs themselves). The tool LOGIC here is a compact
mirror of ``src/tools.ts``; the ``mcp`` SDK provides the stdio transport.

The pure functions (``load_index``, ``run_tool``, ``TOOL_SPECS``) are stdlib-only and importable
without the ``mcp`` package, so they can be tested directly. Only ``serve`` imports ``mcp``.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

_INDEX_PATH = Path(__file__).parent / "_data" / "index.json"


def load_index() -> dict[str, Any]:
    """Load the bundled docs index. Raises a clear error if the build step never ran."""
    if not _INDEX_PATH.exists():
        raise FileNotFoundError(
            f"docs index missing at {_INDEX_PATH}. It is generated by the Node build "
            "(`pnpm build:index` from the repo root, which also writes it here). See PUBLISHING.md."
        )
    return json.loads(_INDEX_PATH.read_text(encoding="utf-8"))


# ---------- shared helpers (mirror src/tools.ts) ----------


def _norm(s: str) -> str:
    return re.sub(r"[^a-z0-9]", "", s.lower())


def _norm_lang(x: Any) -> str | None:
    if not x:
        return None
    s = str(x).lower()
    if s.startswith("py"):
        return "python"
    if s.startswith(("ts", "type", "js", "java")):
        return "ts"
    return None


def _version_footer(index: dict[str, Any]) -> str:
    site = index["meta"]["site"]
    as_of = index["versions"].get("asOf", "")
    stamp = f" (as of {as_of})" if as_of else ""
    return (
        f"\n---\nCall-shapes are verified against the current published release{stamp}. "
        f"Exact per-package versions (PyPI `cendor-*` / npm `@cendor/*`): {site}/releases · "
        f"Full trap table & examples: {site}/docs/for-ai-assistants"
    )


# ---------- get_api ----------


def _score_trap(row: dict[str, Any], symbol: str) -> int:
    q = symbol.lower()
    qc = _norm(symbol)
    score = 0
    for sym in row["symbols"]:
        if sym == q:
            score = max(score, 100)
        elif _norm(sym) == qc:
            score = max(score, 90)
        elif q in sym or sym in q:
            score = max(score, 60)
        elif qc in _norm(sym) and len(qc) >= 3:
            score = max(score, 40)
    if score == 0:
        if qc in _norm(row["task"]) and len(qc) >= 3:
            score = 20
    return score


def _example_for(index: dict[str, Any], symbol: str) -> dict[str, Any] | None:
    qc = _norm(symbol)
    for ex in index["examples"]:
        if any(_norm(k) == qc or qc in _norm(k) for k in ex["keywords"]):
            return ex
    return None


def _render_trap(row: dict[str, Any], lang: str | None) -> str:
    out = [f"### {row['task']}"]
    if lang in (None, "python"):
        out.append(f"- **Python** — {row['python']}")
    if lang in (None, "ts"):
        out.append(f"- **TypeScript** — {row['typescript']}")
    out.append(f"- **Trap** — {row['trap']}")
    return "\n".join(out)


# ---------- example ----------


def _score_example(ex: dict[str, Any], task: str) -> int:
    terms = [t for t in re.split(r"[^a-z0-9]+", task.lower()) if len(t) > 1]
    hay = f"{ex['title']} {' '.join(ex['keywords'])}".lower()
    score = 0
    kws = {k.lower() for k in ex["keywords"]}
    for t in terms:
        if t in kws:
            score += 5
        elif t in hay:
            score += 2
    return score


def _render_example(ex: dict[str, Any], lang: str | None) -> str:
    out = [f"### {ex['title']}"]
    if lang in (None, "python") and ex["python"]:
        out.append(f"```python\n{ex['python']}\n```")
    if lang in (None, "ts") and ex["typescript"]:
        out.append(f"```ts\n{ex['typescript']}\n```")
    return "\n\n".join(out)


# ---------- get_page ----------


def _find_page(index: dict[str, Any], raw_slug: str) -> tuple[str, list[dict[str, Any]]]:
    slug = re.sub(r"^/?docs/", "", raw_slug.strip())
    slug = slug.lstrip("/").rstrip("/")
    product_hint: str | None = None
    m = re.match(r"^(libraries|libs|sdk|parity)[:/](.+)$", slug)
    if m:
        product_hint = "libraries" if m.group(1) == "libs" else m.group(1)
        slug = m.group(2)
    if slug in ("", "docs"):
        slug = "index"
    matches = [
        p
        for p in index["pages"]
        if p["slug"] == slug and (not product_hint or p["product"] == product_hint)
    ]
    return slug, matches


# ---------- search ----------


def _tokenize(s: str) -> list[str]:
    return [t for t in re.findall(r"[a-z0-9_.]+", s.lower()) if len(t) > 1]


def _search_docs(index: dict[str, Any], query: str, limit: int = 6) -> list[dict[str, Any]]:
    terms = _tokenize(query)
    if not terms:
        return []
    hits = []
    for chunk in index["chunks"]:
        hay_title = f"{chunk['title']} {chunk['heading']}".lower()
        hay_text = chunk["text"].lower()
        score = 0
        for t in terms:
            if t in hay_title:
                score += 6
            score += min(hay_text.count(t), 5)
        if score > 0:
            flat = re.sub(r"\s+", " ", chunk["text"]).strip()
            hits.append(
                {
                    "title": chunk["title"],
                    "url": chunk["url"],
                    "product": chunk["product"],
                    "snippet": (flat[:240] + "…") if len(flat) > 240 else flat,
                    "score": score,
                }
            )
    hits.sort(key=lambda h: h["score"], reverse=True)
    return hits[:limit]


