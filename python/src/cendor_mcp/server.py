def run_tool(index: dict[str, Any], name: str, args: dict[str, Any]) -> str:
    handler = _HANDLERS.get(name)
    if handler is None:
        return f"Unknown tool: {name}"
    return handler(index, args)


# ---------- mcp stdio server (imports the mcp SDK lazily) ----------


async def serve() -> None:
    import mcp.types as types
    from mcp.server import Server
    from mcp.server.stdio import stdio_server

    index = load_index()
    server: Server = Server("cendor-mcp")

    @server.list_tools()
    async def _list_tools() -> list[types.Tool]:  # pyright: ignore[reportUnusedFunction]
        return [
            types.Tool(
                name=t["name"],
                title=t["title"],
                description=t["description"],
                inputSchema=t["inputSchema"],
            )
            for t in TOOL_SPECS
        ]

    @server.call_tool()
    async def _call_tool(  # pyright: ignore[reportUnusedFunction]
        name: str, arguments: dict[str, Any]
    ) -> list[types.TextContent]:
        return [types.TextContent(type="text", text=run_tool(index, name, arguments or {}))]

    async with stdio_server() as (read, write):
        await server.run(read, write, server.create_initialization_options())
